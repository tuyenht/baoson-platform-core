<?php

namespace App\Console\Commands;

use App\Enums\Permission as P;
use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;

class RbacExportPermissions extends Command
{
    /**
     * Output path is relative to control-plane base.
     */
    protected $signature = 'rbac:export-permissions {--path=resources/js/types/permissions.generated.ts : Output path relative to app base}';

    protected $description = 'Export canonical permissions to a generated TypeScript module (type-safe frontend).';

    public function handle(Filesystem $fs): int
    {
        $outRel = (string) $this->option('path');
        $outPath = base_path($outRel);

        $lines = [];
        $lines[] = '/* eslint-disable */';
        $lines[] = '/**';
        $lines[] = ' * AUTO-GENERATED FILE. DO NOT EDIT.';
        $lines[] = ' *';
        $lines[] = ' * Source of truth: app/Enums/Permission.php (App\\Enums\\Permission)';
        $lines[] = ' * Generated by: php artisan rbac:export-permissions';
        $lines[] = ' */';
        $lines[] = '';
        $lines[] = 'export const PERMISSIONS = {';

        foreach (P::cases() as $case) {
            $key = $case->name;
            $value = $case->value;
            $lines[] = "  {$key}: ".json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE).',';
        }

        $lines[] = '} as const;';
        $lines[] = '';
        $lines[] = 'export type PermissionName = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];';
        $lines[] = '';
        $lines[] = 'export const PERMISSION_VALUES = Object.values(PERMISSIONS) as PermissionName[];';
        $lines[] = '';

        $dir = dirname($outPath);
        if (! $fs->exists($dir)) {
            $fs->makeDirectory($dir, 0755, true);
        }

        $fs->put($outPath, implode("\n", $lines));

        $this->info("Exported permissions to: {$outRel}");
        $this->line('Count: '.count(P::cases()));

        return self::SUCCESS;
    }
}


